"""Generate the docs site's check catalog from checks/*.yaml.

    uv run python scripts/gen_check_docs.py            # write docs/checks/
    uv run python scripts/gen_check_docs.py --check    # fail if docs/checks/ is stale

The YAML catalog is the single source; tests/test_docs.py fails when the
committed pages no longer match it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from mcpprobe.engine.catalog import Check, Suite, load_catalog

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "checks"
SUITE_TITLES = {
    Suite.CONF: "Conformance (CONF)",
    Suite.FUZZ: "Schema fuzzing (FUZZ)",
    Suite.ROB: "Robustness (ROB)",
    Suite.SEC: "Security (SEC)",
    Suite.EVAL: "Tool-usability eval (EVAL)",
}
HEADER = "<!-- Generated by scripts/gen_check_docs.py from checks/*.yaml. Do not edit. -->\n\n"


ERAS = {
    "modern": "modern era",
    "legacy": "legacy era",
    "both": "both eras",
    "dual": "dual-era servers",
}


def _where(check: Check) -> str:
    transports = ", ".join(t.value for t in check.transports)
    return f"{ERAS[check.era.value]}, {transports}"


def check_page(check: Check) -> str:
    return (
        f"{HEADER}# {check.id}: {check.title}\n\n"
        f"| Severity | Applies to | Spec section |\n|---|---|---|\n"
        f"| {check.severity.value} | {_where(check)} | {_link(check.spec_ref)} |\n\n"
        f"{check.description}\n\n"
        f"From the command line: `mcpprobe checks explain {check.id}`. To leave it out of a run, "
        f'add `"{check.id}"` to `[checks] disable` in [mcpprobe.toml](../configuration.md); to '
        f"change how much it counts, use `severity_overrides`.\n"
    )


def _link(url: str) -> str:
    return f"[{_short(url)}]({url})"


def _short(url: str) -> str:
    return url.split("/specification/", 1)[-1]


def index_page(catalog: tuple[Check, ...]) -> str:
    lines = [
        HEADER,
        "# Check catalog\n\n",
        "Every check cites the section of the MCP specification it enforces. `error` checks "
        "enforce a MUST and fail the run; `warn` checks enforce a SHOULD or flag a heuristic; "
        "`info` checks are advice. Crashes and hangs fail the run whatever the check's "
        "severity.\n",
    ]
    for suite, title in SUITE_TITLES.items():
        checks = [c for c in catalog if c.suite is suite]
        if not checks:
            continue
        lines.append(f"\n## {title}\n\n| ID | Severity | Applies to | Check |\n|---|---|---|---|\n")
        lines.extend(
            f"| [{c.id}]({c.id}.md) | {c.severity.value} | {_where(c)} | {c.title} |\n"
            for c in checks
        )
    return "".join(lines)


def render(catalog: tuple[Check, ...]) -> dict[str, str]:
    pages = {"index.md": index_page(catalog)}
    pages.update({f"{c.id}.md": check_page(c) for c in catalog})
    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/checks is out of date")
    args = parser.parse_args(argv)
    pages = render(load_catalog(ROOT / "checks"))
    if args.check:
        stale = sorted(
            name
            for name, text in pages.items()
            if not (OUT / name).is_file() or (OUT / name).read_text(encoding="utf-8") != text
        )
        extra = sorted(p.name for p in OUT.glob("*.md") if p.name not in pages)
        if stale or extra:
            print(
                f"docs/checks is stale: {stale + extra}; run scripts/gen_check_docs.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        if old.name not in pages:
            old.unlink()
    for name, text in pages.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(pages)} pages to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
